# Ported from tdutils/td/utils/unicode.cpp, get_unicode_simple_category().
def get_unicode_simple_category(code: int) -> int:
    """Return the simple category of the code point `code`, one of `CATEGORY`.

    `code` must be at most U+10FFFF.
    """
    if code < 128:
        return _UNICODE_SIMPLE_CATEGORY_TABLE[code]
    if code <= 0x20000:
        jump_pos_index = code >> 7
    else:
        jump_pos_index = (0x20000 >> 7) - (0x20000 >> 16) + (code >> 16)
    it = _UNICODE_SIMPLE_CATEGORY_JUMP_POS[jump_pos_index]
    code = (code << 5) + 30
    while _UNICODE_SIMPLE_CATEGORY_RANGES[it] <= code:
        it += 1
    return _UNICODE_SIMPLE_CATEGORY_RANGES[it - 1] & 31


# Ported from tdutils/td/utils/unicode.cpp, binary_search_ranges().
def _binary_search_ranges(ranges: tuple[int, ...], code: int) -> int:
    """Return what `ranges` map the code point `code` to, or 0 past U+10FFFF.

    The C++ computes in unsigned 32-bit integers, which the port keeps by masking.
    """
    if code > 0x10FFFF:
        return 0

    left = 0
    right = len(ranges)
    while left < right:
        middle = ((left + right + 2) >> 2) << 1
        if ranges[middle] <= code:
            left = middle
        else:
            right = middle - 2

    t = ranges[left + 1]
    if t < 0:
        return (code - ranges[left] + ~t) & 0xFFFFFFFF
    if t <= 0x10FFFF:
        return t
    match t - 0x200000:
        case 0:
            return code & -2
        case 1:
            return code | 1
        case 2:
            return ((code - 1) | 1) & 0xFFFFFFFF
        case _:
            # Upstream stops with a fatal error here, which no value of its tables
            # reaches.
            return 0


# Ported from tdutils/td/utils/unicode.cpp, unicode_to_lower().
def unicode_to_lower(code: int) -> int:
    """Return the lowercase form of the code point `code`, or 0 past U+10FFFF."""
    if code < _TABLE_SIZE:
        return _TO_LOWER_TABLE[code]
    return _binary_search_ranges(_TO_LOWER_RANGES, code)
